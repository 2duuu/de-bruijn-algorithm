// Aggregates the raw lambda sweep CSVs (data/raw/<sweep>/results.csv) into
// data/lambda-data.js: replicate mean and sample std per (x, series).
// No values are invented or smoothed; every number comes from the CSVs.
// Usage: node tools/aggregate.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const raw = path.join(root, "data", "raw");

function readCsv(file) {
  const lines = fs.readFileSync(file, "utf8").trim().split(/\r?\n/);
  const head = lines[0].split(",");
  return lines.slice(1).map((l) => {
    const cells = l.split(",");
    const o = {};
    head.forEach((h, i) => {
      const v = cells[i];
      o[h] = v === "" ? null : v === "True" ? true : v === "False" ? false : isNaN(+v) ? v : +v;
    });
    return o;
  });
}

const FIELDS = ["components", "imbalance", "degradation", "frag_term", "imbalance_term",
  "n_nodes", "n_edges", "n_errors", "missing_kmer_frac", "repeat_collapse_frac"];

function aggregate(rows) {
  const groups = new Map();
  for (const r of rows) {
    const key = `${r.x}|${r.series}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(r);
  }
  const out = [];
  for (const rs of groups.values()) {
    const o = { x: rs[0].x, series: rs[0].series, n: rs.length };
    for (const f of FIELDS) {
      const v = rs.map((r) => r[f]);
      const m = v.reduce((a, b) => a + b, 0) / v.length;
      const sd = v.length > 1 ? Math.sqrt(v.reduce((a, b) => a + (b - m) ** 2, 0) / (v.length - 1)) : 0;
      o[f] = +m.toPrecision(6);
      o[f + "_sd"] = +sd.toPrecision(4);
    }
    out.push(o);
  }
  return out.sort((a, b) => (a.series ?? 0) - (b.series ?? 0) || a.x - b.x);
}

const sweeps = ["coverage_sweep", "error_sweep", "kmer_sweep", "kmer_sweep_c10",
  "kmer_sweep_c15", "kmer_sweep_c20", "kmer_sweep_c25"];
const data = { genome: { name: "Enterobacteria phage lambda", accession: "NC_001416.1", length: 48502, circular: false }, sweeps: {} };
for (const s of sweeps) {
  const cfg = JSON.parse(fs.readFileSync(path.join(raw, s, "config.json"), "utf8"));
  const rows = readCsv(path.join(raw, s, "results.csv"));
  data.sweeps[s] = {
    config: { read_length: cfg.base.read_length, coverage: cfg.base.coverage ?? null, k: cfg.base.k ?? null,
      error_rate: cfg.base.error_rate ?? null, x: cfg.x.param, series: cfg.series?.param ?? null, replicates: cfg.replicates },
    points: aggregate(rows),
  };
}
// The kmer_sweep (c = 30) is the main k-mer plot; label coverage explicitly.
data.sweeps.kmer_sweep.config.coverage = 30;

const js = "// AUTO-GENERATED by tools/aggregate.mjs from data/raw/*/results.csv. Do not edit by hand.\n" +
  "window.LAMBDA_DATA = " + JSON.stringify(data) + ";\n";
fs.writeFileSync(path.join(root, "data", "lambda-data.js"), js);

